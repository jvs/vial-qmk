void render_stacked_letters(const char* const letters[], int count) {
    // Each letter is 24 pixels tall (3 OLED rows)
    // OLED is 128 pixels tall, so we have room for 5 letters
    for (int i = 0; i < count && i < 5; i++) {
        int start_page = i * 3;  // 3 pages per letter

        for (int page = 0; page < 3; page++) {
            oled_set_cursor(0, start_page + page);
            oled_write_raw_P(&letters[i][page * 24], 24);
        }

        //
        // Set position for each letter - each letter takes 3 rows (24 pixels)
        // oled_set_cursor(0, i * 3);
        // oled_write_raw_P(letters[i], 72);
    }
}

void render_simple_vertical_text(const char* text) {
    for (int i = 0; text[i] != '\0'; i++) {
        oled_set_cursor(0, i);
        oled_write_char(text[i], false);
    }
}

void render_left_display(void) {
    uint8_t current_layer = get_highest_layer(layer_state);

    // Only redraw if layer changed
    if (current_layer != last_left_layer) {
        last_left_layer = current_layer;
        oled_clear();

        switch (current_layer) {
            case _MAIN:
                // Leave blank for main layer
                break;
            case _LOWER:
                {
                    const char* const letters[] = {large_L};
                    render_stacked_letters(letters, 1);
                    // const char* const letters[] = {large_L, large_O, large_W, large_E, large_R};
                    // render_stacked_letters(letters, 5);
                }
                break;
            case _RAISE:
                {
                    const char* const letters[] = {large_R};
                    render_stacked_letters(letters, 1);
                    // const char* const letters[] = {large_R, large_A, large_I, large_S, large_E};
                    // render_stacked_letters(letters, 5);
                }
                break;
            case _MISC:
                {
                    const char* const letters[] = {large_M};
                    render_stacked_letters(letters, 1);
                }
                break;
            case _VIM:
                {
                    const char* const letters[] = {large_V};
                    render_stacked_letters(letters, 1);
                    // const char* const letters[] = {large_V, large_I, large_M};
                    // render_stacked_letters(letters, 3);
                }
                break;
            case _SYMBOL:
                {
                    const char* const letters[] = {large_S};
                    render_stacked_letters(letters, 1);
                }
                break;
            default:
                {
                    const char* const letters[] = {large_M};
                    render_stacked_letters(letters, 1);
                }
                break;
        }
    }
}

void render_right_display(void) {
    uint8_t current_layer = get_highest_layer(layer_state);

    // Only redraw if layer, vim mode, or OS changed
    bool needs_redraw = (current_layer != last_right_layer) ||
                       (current_layer == _VIM && current_vim_mode != last_vim_mode) ||
                       os_changed;

    if (needs_redraw) {
        last_right_layer = current_layer;
        last_vim_mode = current_vim_mode;
        os_changed = false;  // Clear the flag after handling
        oled_clear();

        if (current_layer == _VIM) {
            // Show vim mode
            switch (current_vim_mode) {
                case VIM_NORMAL:
                    render_simple_vertical_text("N");
                    break;
                case VIM_VISUAL:
                    render_simple_vertical_text("V");
                    break;
            }
        } else if (current_layer == _SYMBOL) {
            // Show symbol layer active
            render_simple_vertical_text("S");
        } else {
            // Show current OS horizontally
            if (current_os == OS_MAC) {
                oled_write_P(PSTR("MAC"), false);
            } else {
                oled_write_P(PSTR("WIN"), false);
            }
        }
    }
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        render_left_display();
    } else {
        render_right_display();
    }
    return false;
}

