// Leader sequence helper functions
static void reset_leader_sequence(void);
static void end_leader_sequence(void);
static bool process_leader_sequence(void);
static bool is_partial_match(void);

// Leader sequence helper functions implementation
static void reset_leader_sequence(void) {
    leader_active = false;
    leader_sequence_pos = 0;
    memset(leader_sequence, 0, sizeof(leader_sequence));
    layer_off(_LEADER);
}

static void end_leader_sequence(void) {
    reset_leader_sequence();
}

static bool process_leader_sequence(void) {
    // Check for complete matches
    for (uint8_t i = 0; i < LEADER_COMBO_COUNT; i++) {
        if (strcmp(leader_sequence, leader_combos[i].sequence) == 0) {
            // Found a match - output the result
            tap_code16(leader_combos[i].output_keycode);
            end_leader_sequence();
            return true;
        }
    }
    return false;
}

static bool is_partial_match(void) {
    // Check if current sequence is a prefix of any combo
    for (uint8_t i = 0; i < LEADER_COMBO_COUNT; i++) {
        if (strncmp(leader_sequence, leader_combos[i].sequence, leader_sequence_pos) == 0) {
            return true;
        }
    }
    return false;
}

// Get effective OS (manual override or default)
custom_os_t get_effective_os(void) {
    if (os_override != CUSTOM_OS_AUTO) {
        return os_override;
    }

    // Default to macOS when in auto mode (no detection available)
    return CUSTOM_OS_MACOS;
}

// Cycle through OS override options
static void cycle_os_override(void) {
    switch (os_override) {
        case CUSTOM_OS_AUTO:
            os_override = CUSTOM_OS_WINDOWS;  // Skip MAC since AUTO defaults to MAC
            break;
        case CUSTOM_OS_MACOS:
            os_override = CUSTOM_OS_WINDOWS;
            break;
        case CUSTOM_OS_WINDOWS:
            os_override = CUSTOM_OS_LINUX;
            break;
        case CUSTOM_OS_LINUX:
            os_override = CUSTOM_OS_AUTO;
            break;
    }
}

